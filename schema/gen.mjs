// Generates supabase/migrations/002_tables.sql + 003_policies.sql and src/lib/entities.gen.ts from schema/tables.mjs.
// Tables are emitted as compact app.t(...) calls; the builder function itself lives in 001_core.sql.
import { writeFileSync } from 'node:fs';
import { TABLES } from './tables.mjs';

function parseCol(spec) {
  let m = spec.match(/^(\w+)>(\w+)(!)?$/);
  if (m) return { key: m[1], type: 'uuid', ref: m[2], req: !!m[3] };
  m = spec.match(/^(\w+)(?::(\w+))?(!)?(.*)$/);
  if (!m) throw new Error('bad col ' + spec);
  const type = m[2] || 'text';
  let rest = m[4], def, opts;
  if (rest.startsWith('=')) {
    if (type === 'jsonb') { def = rest.slice(1); rest = ''; }
    else { const i = rest.indexOf('{'); def = i < 0 ? rest.slice(1) : rest.slice(1, i); rest = i < 0 ? '' : rest.slice(i); }
  }
  if (rest.startsWith('{')) opts = rest.slice(1, -1).split('|');
  else if (rest) throw new Error('bad col ' + spec);
  return { key: m[1], type, req: !!m[3], def, opts };
}
const titleCase = (s) => s.replace(/_id$/, '').replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase());
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

let tables = `-- GENERATED by schema/gen.mjs from schema/tables.mjs. Do not edit by hand.\n`;
let extra = '';
const ents = {};
for (const t of TABLES) {
  const cols = t.cols.map(parseCol);
  if (t.cols.some((c) => c.includes(';'))) throw new Error('semicolon in col spec: ' + t.name);
  const o = {};
  if (t.branch) o.branch = true;
  if (t.year) o.year = true;
  if (t.custom) o.custom = true;
  if (t.readAll) o.read_all = true;
  if (t.student) o.student = t.student === true ? 'student_id' : t.student;
  if (t.own) o.own = t.own;
  if (t.staffOwn) o.staff_own = t.staffOwn === true ? 'staff_id' : t.staffOwn;
  if (t.noStaffRead) o.no_staff_read = true;
  if (t.audit === false) o.audit = 'none'; else if (t.audit === 'ud') o.audit = 'ud';
  if (t.unique) o.unique = t.unique.map((u) => u.join(','));
  if (t.index) o.index = t.index.map((u) => u.join(','));
  tables += `select app.t(${q(t.name)},${q(t.cap)},${q(t.cols.join(';'))},${q(JSON.stringify(o))});\n`;
  if (t.sql) extra += t.sql.trim() + '\n';

  const label = t.label || (cols.find((c) => ['name', 'title'].includes(c.key)) || cols[0]).key;
  ents[t.name] = {
    table: t.name, title: t.title || titleCase(t.name), module: t.module, cap: t.cap,
    label: Array.isArray(label) ? label : [label], branch: !!t.branch, year: !!t.year, custom: !!t.custom,
    hidden: !!t.hidden, readonly: !!t.readonly, desc: t.desc || '',
    list: t.list || cols.filter((c) => c.type !== 'jsonb' && !(t.hide || []).includes(c.key)).slice(0, 6).map((c) => c.key),
    fields: cols.filter((c) => !(t.hide || []).includes(c.key)).map((c) => ({
      k: c.key, label: titleCase(c.key),
      t: c.ref ? 'ref' : c.opts ? 'select' : ({ int: 'number', numeric: 'number', bool: 'bool', date: 'date', time: 'time', ts: 'datetime', jsonb: 'json', uuid: 'uuid' }[c.type] || (/(notes?|body|description|plan|details|address|reason|remark|resolution|comments?|question|outcomes|items|instructions|review|goals)$/.test(c.key) ? 'textarea' : 'text')),
      ...(c.ref ? { ref: c.ref } : {}), ...(c.opts ? { opts: c.opts } : {}), ...(c.req ? { req: true } : {}), ...(c.def !== undefined && c.def !== '' && !['now', 'today', 'uid'].includes(c.def) ? { def: c.def } : {}),
    })),
  };
}
tables += `select app.run_pending(1);\n`;
writeFileSync(new URL('../supabase/migrations/002_tables.sql', import.meta.url), tables);

const policies = `-- GENERATED by schema/gen.mjs. Family helpers, generated policies, then table-specific policies.
create or replace function app.my_households() returns uuid[] language sql stable security definer set search_path = '' as
$$ select coalesce(array_agg(household_id), '{}') from public.guardians where user_id = auth.uid() $$;
create or replace function app.my_students() returns uuid[] language sql stable security definer set search_path = '' as
$$ select coalesce(array_agg(s.id), '{}') from public.students s
   where s.household_id = any(app.my_households()) or s.id = (select student_id from public.profiles where id = auth.uid()) $$;
create or replace function app.my_sections() returns uuid[] language sql stable security definer set search_path = '' as
$$ select coalesce(array_agg(distinct section_id), '{}') from public.students where id = any(app.my_students()) and section_id is not null $$;
create or replace function app.my_routes() returns uuid[] language sql stable security definer set search_path = '' as
$$ select coalesce(array_agg(distinct route_id), '{}') from public.student_transport where student_id = any(app.my_students()) and active $$;
alter table public.profiles add constraint profiles_branch_id_fkey foreign key (branch_id) references public.branches(id) on delete set null;
alter table public.profiles add constraint profiles_staff_id_fkey foreign key (staff_id) references public.staff(id) on delete set null;
alter table public.profiles add constraint profiles_student_id_fkey foreign key (student_id) references public.students(id) on delete set null;
select app.run_pending(2);
${extra}`;
writeFileSync(new URL('../supabase/migrations/003_policies.sql', import.meta.url), policies);

writeFileSync(new URL('../src/lib/entities.gen.ts', import.meta.url), `// GENERATED by schema/gen.mjs. Do not edit by hand.
export type FieldDef = { k: string; label: string; t: 'text' | 'textarea' | 'number' | 'bool' | 'date' | 'time' | 'datetime' | 'json' | 'uuid' | 'select' | 'ref'; ref?: string; opts?: string[]; req?: boolean; def?: string };
export type EntityDef = { table: string; title: string; module: string; cap: string; label: string[]; branch: boolean; year: boolean; custom: boolean; hidden: boolean; readonly: boolean; desc: string; list: string[]; fields: FieldDef[] };
export const ENTITIES: Record<string, EntityDef> = ${JSON.stringify(ents)};
`);
console.log(`generated ${TABLES.length} tables`);
